#!/usr/bin/env python3
"""Generate Adafruit-GFX style font headers from DejaVu TTFs.

Usage: python3 tools/gen_fonts.py   (needs Pillow)
Output: lib/core/src/fonts/font_<name>.h
Code points: 0x20-0x7E, 0xA0-0xFF, plus U+2026 stored at 0x7F.
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "tools", "fonts")
OUT = os.path.join(ROOT, "lib", "core", "src", "fonts")

FONTS = [
    ("Small", "DejaVuSans.ttf", 11),
    ("Body", "DejaVuSans.ttf", 14),
    ("BodyBold", "DejaVuSans-Bold.ttf", 14),
    ("Title", "DejaVuSans-Bold.ttf", 18),
    ("Huge", "DejaVuSans-Bold.ttf", 40),
]

CODES = [(c, c) for c in range(0x20, 0x7F)] + [(0x7F, 0x2026)] + [(c, c) for c in range(0xA0, 0x100)]


def gen(name, ttf, size):
    font = ImageFont.truetype(os.path.join(TTF, ttf), size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    for code, uni in CODES:
        ch = chr(uni)
        adv = int(round(font.getlength(ch)))
        # render 1-bit (no antialiasing) on a canvas with baseline at y=ascent
        pad = size
        img = Image.new("1", (adv + 2 * pad, ascent + descent + 2 * pad), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((pad, pad), ch, font=font, fill=1)
        bbox = img.getbbox()
        offset = len(bitmap)
        if bbox is None:
            glyphs.append((offset, 0, 0, adv, 0, 0))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        bits = []
        for y in range(y0, y1):
            for x in range(x0, x1):
                bits.append(1 if img.getpixel((x, y)) else 0)
        while len(bits) % 8:
            bits.append(0)
        for i in range(0, len(bits), 8):
            v = 0
            for b in bits[i:i + 8]:
                v = (v << 1) | b
            bitmap.append(v)
        glyphs.append((offset, w, h, adv, x0 - pad, y0 - pad - ascent))
    lines = ["// Generated by tools/gen_fonts.py - do not edit.", "#pragma once", '#include "gfxfont.h"', ""]
    lines.append(f"static const uint8_t font{name}Bitmaps[] = {{")
    for i in range(0, len(bitmap), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const GFXglyph font{name}Glyphs[] = {{")
    for g in glyphs:
        lines.append("  {%d, %d, %d, %d, %d, %d}," % g)
    lines.append("};")
    lines.append(f"static const GFXfont font{name} = {{font{name}Bitmaps, font{name}Glyphs, 0x20, 0xFF, {ascent + descent}, {ascent}}};")
    path = os.path.join(OUT, f"font_{name.lower()}.h")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(path, len(bitmap), "bytes")


if __name__ == "__main__":
    for n, t, s in FONTS:
        gen(n, t, s)
